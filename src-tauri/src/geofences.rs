/// Smallest static box containing the point, if any.
pub fn static_geofence(lat: f64, lon: f64) -> Option<&'static str> {
    let mut best: Option<(&'static str, f64)> = None;
    for (label, min_lat, max_lat, min_lon, max_lon) in STATIC_GEOFENCES {
        if lat >= *min_lat && lat <= *max_lat && lon >= *min_lon && lon <= *max_lon {
            let area = (max_lat - min_lat) * (max_lon - min_lon);
            if best.map_or(true, |(_, a)| area < a) {
                best = Some((label, area));
            }
        }
    }
    best.map(|(label, _)| label)
}